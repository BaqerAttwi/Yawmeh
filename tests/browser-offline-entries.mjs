import assert from 'node:assert/strict';
import {once} from 'node:events';
import {isAbsolute} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createApp} from '../server/src/app.js';
import {memoryDatabase} from './helpers/memory-db.js';

const module=process.env.PLAYWRIGHT_MODULE||'playwright';
const {chromium}=await import(isAbsolute(module)?pathToFileURL(module).href:module);
const user={id:1,name:'Offline Tester',email:'offline@test.local',role:'user',active:true,permissions:['money','tasks']};
const records={};
const server=createApp({db:memoryDatabase(records,[user]),authStore:{session:async()=>user},recoveryOptions:null}).listen(0,'127.0.0.1');
await once(server,'listening');
const url=`http://127.0.0.1:${server.address().port}`;
let browser;
try{
  browser=await chromium.launch({headless:true,channel:'msedge'});
  const context=await browser.newContext({viewport:{width:390,height:844}});
  await context.addCookies([{name:'daywell_session',value:'a'.repeat(64),url}]);
  const page=await context.newPage();
  await page.goto(url);
  await page.waitForFunction(()=>navigator.serviceWorker.controller&&localStorage.getItem('yawmeh:offline-account'));
  await page.getByRole('button',{name:'Close getting started'}).click();
  await page.locator('.sync-status').getByText('Synced · works offline',{exact:true}).waitFor();
  await context.setOffline(true);
  await page.reload();
  await page.getByRole('heading',{name:'Offline capture'}).waitFor();
  await page.getByLabel('Type').selectOption('income');
  await page.getByLabel('Description').fill('Offline income');
  await page.getByLabel('Amount').fill('10');
  await page.getByRole('button',{name:'Save on this device'}).click();
  await page.getByText('1 pending sync.',{exact:true}).waitFor();
  await page.reload();
  await page.getByText('1 pending sync.',{exact:true}).waitFor();
  await page.getByLabel('Description').fill('Coffee');
  await page.getByLabel('Amount').fill('3');
  await page.getByRole('button',{name:'Save on this device'}).click();
  await page.getByText('2 pending sync.',{exact:true}).waitFor();
  await page.getByLabel('Task name').fill('Offline task');
  await page.getByRole('button',{name:'Save task on this device'}).click();
  await page.getByLabel('Note',{exact:true}).fill('Offline inbox note');
  await page.getByRole('button',{name:'Save note on this device'}).click();
  await page.reload();
  await page.getByText('4 pending sync.',{exact:true}).waitFor();
  await page.getByText('Pending records',{exact:true}).click();
  await page.getByText('Offline inbox note · Pending sync',{exact:true}).waitFor();
  assert.equal(records.entries.length,0);
  await context.setOffline(false);
  await page.getByText('4 synced.',{exact:true}).waitFor();
  assert.deepEqual(records.entries.map(entry=>entry.title),['Offline income','Coffee']);
  assert.deepEqual(records.tasks.map(task=>task.title),['Offline task']);
  assert.deepEqual(records.inbox.map(note=>note.text),['Offline inbox note']);
  await page.getByRole('link',{name:'Return to workspace'}).click();
  await page.locator('.sync-status').getByText('Synced · works offline',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.startsWith('yawmeh:offline-entry:')).length),0);
  await context.setOffline(true);
  await page.getByRole('button',{name:'Log expense',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.locator('[name=title]').fill('Expense over balance');
  await dialog.locator('[name=amount]').fill('20');
  await dialog.getByRole('button',{name:'Save transaction'}).click();
  await page.getByText('Pending records (1)',{exact:true}).waitFor();
  await context.setOffline(false);
  const review=page.getByRole('region',{name:'Offline queue'});
  await review.getByText('Expense over balance',{exact:true}).waitFor();
  await review.getByText(/Insufficient spending balance/).waitFor();
  assert.equal(records.entries.length,2);
  await review.getByRole('button',{name:'Edit',exact:true}).click();
  const correction=review.getByRole('form',{name:'Edit pending record'});
  await correction.getByLabel('Description').fill('Corrected expense');
  await correction.getByLabel('Amount (USD)').fill('5');
  await correction.getByRole('button',{name:'Save correction'}).click();
  await review.getByText('Pending records (1)',{exact:true}).waitFor({state:'hidden'});
  assert.deepEqual(records.entries.map(entry=>entry.title),['Offline income','Coffee','Corrected expense']);
}finally{
  await browser?.close();
  server.closeAllConnections();
  server.close();
}
