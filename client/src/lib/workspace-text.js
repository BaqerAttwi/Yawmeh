export function workspaceText(language){
 return (message,values={})=>{
  const translated=language==='ar'&&Object.hasOwn(arabic,message)?arabic[message]:message;
  return translated.replace(/\{(\w+)\}/g,(match,key)=>Object.hasOwn(values,key)?values[key]:match);
 };
}
